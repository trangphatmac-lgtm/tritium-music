#!/usr/bin/env python3
"""Import BridgeAssist's literal setting constructors from the supplied RavenBs source.

Fail on unsupported constructors so a source update cannot silently omit an option.
The shared schema uses the same zero-based slider rounding as RavenBs SliderSetting.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('bridge_assist', type=Path)
    args = parser.parse_args()
    raw = args.bridge_assist.read_bytes()
    source = raw.decode('utf-8')
    settings = []
    constructors = re.findall(r'new (SliderSetting|ButtonSetting|DescriptionSetting)\(([^\n;]*)\)', source)
    if len(constructors) != source.count('this.registerSetting('):
        raise ValueError('Unsupported setting registration in BridgeAssist')
    for kind, arguments in constructors:
        # Registration adds a closing parenthesis after the constructor.
        values = json.loads('[' + arguments.rstrip(')') + ']')
        if kind == 'SliderSetting' and len(values) == 6:
            name, suffix, default, minimum, maximum, step = values
            settings.append(dict(t='slider', name=name, prefix='', suffix=suffix,
                                 value=default, min=minimum, max=maximum, step=step,
                                 options=None, labels=None))
        elif kind == 'ButtonSetting' and len(values) == 2 and isinstance(values[1], bool):
            settings.append(dict(t='toggle', name=values[0], value=values[1]))
        elif kind == 'DescriptionSetting' and len(values) == 1:
            settings.append(dict(t='desc', name=values[0]))
        else:
            raise ValueError('Unsupported setting: ' + kind + '(' + arguments + ')')
    module = dict(id='bridgeAssist', name='Bridge Assist', category='player', settings=settings)
    root = Path(__file__).resolve().parents[2]
    quote = lambda value: json.dumps(value, ensure_ascii=True)
    lines = ['package tritium.minecraft.protocol;', '', 'import java.util.*;', '',
             '/** Generated by tools/minecraft/import_ravenbs_settings.py; do not hand-edit. */',
             'final class RavenBsCatalog {',
             '    static final String SOURCE_SHA256 = ' + quote(hashlib.sha256(raw).hexdigest()) + ';',
             '    static Map<String, OpenB4Settings.Definition> create() {',
             '        return Collections.singletonMap("bridgeAssist", new OpenB4Settings.Definition(',
             '            "bridgeAssist", "Bridge Assist", ModuleCategory.PLAYER, Arrays.asList(']
    options = []
    for s in settings:
        if s['t'] == 'slider':
            option = ('new OpenB4Settings.Option(%s, %s, %s, %s, %s, "", %s, '
                      'new String[]{}, new double[]{}, new String[]{}, true, -1)' %
                      (quote(s['name']), s['value'], s['min'], s['max'], s['step'], quote(s['suffix'])))
        else:
            option = 'new OpenB4Settings.Option(%s, %s, %s)' % (quote(s['name']), quote(s['t']), str(s.get('value', False)).lower())
        options.append('                ' + option)
    lines.append(',\n'.join(options) + ')));')
    lines.extend(['    }', '    private RavenBsCatalog() { }', '}'])
    (root / 'src/minecraft-shared/java/tritium/minecraft/protocol/RavenBsCatalog.java').write_text('\n'.join(lines) + '\n')
    fixture = root / 'minecraft-agent/src/test/resources/ravenbs-modules.json'
    fixture.parent.mkdir(parents=True, exist_ok=True)
    fixture.write_text(json.dumps([module], indent=2, ensure_ascii=False) + '\n')


if __name__ == '__main__':
    main()
