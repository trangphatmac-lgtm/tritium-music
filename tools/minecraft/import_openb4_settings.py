#!/usr/bin/env python3
"""Regenerate the Java 8 option schema from the user-supplied OpenB4 catalog."""
import argparse
import hashlib
import json
from pathlib import Path

MODULES = {
    'antiKnockback': 'AntiKnockback', 'clickAssist': 'ClickAssist', 'hitSelect': 'Hit Select',
    'jumpReset': 'Jump Reset', 'reach': 'Reach', 'wTap': 'WTap', 'backtrack': 'Backtrack',
    'blink': 'Blink', 'fakeLag': 'Fake Lag', 'lagRange': 'Lag Range', 'autoJump': 'AutoJump',
    'autoLadder': 'AutoLadder', 'autoSwap': 'AutoSwap', 'autoTool': 'AutoTool',
    'delayRemove': 'Delay Remover', 'fastMine': 'FastMine', 'fastPlace': 'FastPlace',
    'safeWalk': 'SafeWalk', 'waterBucket': 'Water Bucket', 'antiDebuff': 'AntiDebuff',
    'bedESP': 'BedESP', 'chams': 'Chams', 'chestESP': 'ChestESP', 'indicators': 'Indicators',
    'itemESP': 'ItemESP', 'nametags': 'Nametags', 'noCameraClip': 'NoCameraClip',
    'noHurtCam': 'NoHurtCam', 'playerESP': 'PlayerESP', 'radar': 'Radar',
    'targetHud': 'TargetHUD', 'tracers': 'Tracers', 'trajectories': 'Trajectories', 'xray': 'Xray',
    'antiBot': 'AntiBot'
}

def quote(s):
    return json.dumps(s, ensure_ascii=True)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('catalog', type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    raw = args.catalog.read_bytes()
    catalog = {m['name']: m for m in json.loads(raw)}
    selected = []
    lines = ['package tritium.minecraft.protocol;', '', 'import java.util.*;', '',
             '/** Generated by tools/minecraft/import_openb4_settings.py; do not hand-edit. */',
             'final class OpenB4Catalog {', '    static final String SOURCE_SHA256 = ' + quote(hashlib.sha256(raw).hexdigest()) + ';',
             '    static Map<String, OpenB4Settings.Definition> create() {',
             '        Map<String, OpenB4Settings.Definition> result = new LinkedHashMap<String, OpenB4Settings.Definition>();']
    for mid, name in MODULES.items():
        module = catalog[name]
        selected.append(dict(module, id=mid))
        lines.append('        result.put(%s, new OpenB4Settings.Definition(%s, %s, ModuleCategory.%s, Arrays.asList(' % (quote(mid), quote(mid), quote(name), module['category'].upper()))
        options = []
        for s in module['settings']:
            kind = s['t']
            if kind in ('toggle', 'button', 'desc'):
                opts = 'new OpenB4Settings.Option(%s, %s, %s)' % (quote(s['name']), quote(kind), str(s.get('value', False)).lower())
            else:
                choices = 'new String[]{' + ', '.join(quote(o) for o in (s.get('options') or [])) + '}'
                labels = s.get('labels') or {}
                label_values = 'new double[]{' + ', '.join(str(float(v)) for v in labels) + '}'
                label_names = 'new String[]{' + ', '.join(quote(v) for v in labels.values()) + '}'
                opts = 'new OpenB4Settings.Option(%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %d)' % (quote(s['name']), s['value'], s['min'], s['max'], s['step'], quote(s.get('prefix', '')), quote(s.get('suffix', '')), choices, label_values, label_names, 'true' if kind == 'slider' else 'false', s.get('compatMax', -1))
            options.append('            ' + opts)
        lines.append(',\n'.join(options) + ')));')
    lines.extend(['        return Collections.unmodifiableMap(result);', '    }', '    private OpenB4Catalog() { }', '}'])
    (root / 'src/minecraft-shared/java/tritium/minecraft/protocol/OpenB4Catalog.java').write_text('\n'.join(lines) + '\n')
    fixture = root / 'minecraft-agent/src/test/resources/openb4-modules.json'
    fixture.parent.mkdir(parents=True, exist_ok=True)
    fixture.write_text(json.dumps(selected, indent=2, ensure_ascii=False) + '\n')

if __name__ == '__main__':
    main()
